"""Runtime loader for the ASCET weakspot testing guidelines knowledge base.

Usage:
    from utils.kb_parser import WEAKSPOT_GUIDELINES, find_block_type

    block_type = find_block_type("Srv_Debounce", WEAKSPOT_GUIDELINES)
    # block_type → "Srv_Debounce"
    guidelines = WEAKSPOT_GUIDELINES.get(block_type, []) if block_type else []

    # Works with suffixed ASCET names too:
    block_type = find_block_type("Srv_DebounceParam_t", WEAKSPOT_GUIDELINES)
    # block_type → "Srv_Debounce"  (Param_t stripped)

The module-level ``WEAKSPOT_GUIDELINES`` dict is loaded once on first import from
``utils/weakspot_guidelines.json`` (generated by ``utils/generate_kb_json.py``).
Returns an empty dict if the JSON file has not been generated yet — all callers
must treat a ``None`` result from ``find_block_type`` as "no guidelines available"
and fall back to rule-based metrics.

RELATIONSHIP TO run.py
----------------------
wrapper-only -- the KB feeds M4 scoring and optional Prompt-2 guideline injection;
NO run.py analog (run.py has no KB).

GROUND-TRUTH run.py = MBD/weakspot_code_to_run_2/run.py. Its per-weakspot pipeline
(run_pipeline) never loads guidelines, never scores, and never augments Prompt 2 with
a knowledge base: Phase 3b (_step_3b_generate_testcases, run.py:465) builds Prompt 2
purely from generate_testcase_prompt(context, filtered_dict, example_output,
instance_names) (run.py:475-477). A repo-wide search of run.py for
"guideline"/"knowledge base"/"KB"/"weakspot_guidelines" returns no matches.

This module exists only in the wrapper and serves two wrapper-only consumers:
  * M4 coverage scoring in evaluation/mbd_metric.py -- resolve_guidelines() supplies the
    validated scenarios M4 checks the generated test cases against (run.py computes NO score).
  * optional Prompt-2 guideline injection -- format_kb_guidelines_block() renders the same
    resolved guidelines as text appended to the test-case generator prompt
    ((corresponds-to) run.py Phase 3b / _step_3b_generate_testcases, run.py:465, whose
    Prompt-2 seed lives VERBATIM in signatures/mbd.py). See MEMORY note
    "Guideline-injection matrix result": injection lifts M4 cosmetically (teaching-to-test)
    but degrades M7/M2, so it is off by default.
The KB layering (new BU-Excel KB -> old HTML KB -> none) is a pure wrapper policy.
"""
from __future__ import annotations

import json                                  # [wrapper-only] read the KB JSON off disk (run.py has no KB)
import re                                    # [wrapper-only] ASCET suffix-stripping regex for block matching
from pathlib import Path                     # [wrapper-only] locate the KB JSON files next to this module
from typing import Dict, List, Optional, Tuple  # [wrapper-only] type hints only

# [wrapper-only] Path to the OLD (HTML-derived) KB, generated by utils/generate_kb_json.py -- no run.py analog.
_KB_JSON = Path(__file__).parent / "weakspot_guidelines.json"

# Path to the NEW (BU FCI Excel-derived) KB, generated by utils/generate_new_kb_json.py.
_NEW_KB_JSON = Path(__file__).parent / "new_weakspot_guidelines.json"

# ── Per-path cache ──────────────────────────────────────────────────────────────
# Keyed by resolved path string so BOTH KBs (old weakspot_guidelines.json + new
# new_weakspot_guidelines.json) can be cached independently. (A single global singleton
# would return the OLD dict for every subsequent load, silently breaking the new KB.)
_guidelines_cache: Dict[str, Dict[str, List[str]]] = {}


# [wrapper-only] Load a KB JSON off disk into a {block -> [guidelines]} dict -- no run.py analog
# (run.py has no KB and never reads weakspot_guidelines.json).
def load_weakspot_guidelines(
    json_path: Optional[Path] = None,
) -> Dict[str, List[str]]:
    """Load a weakspot-guidelines JSON (block name -> [guidelines]).

    Returns an empty dict if the file does not exist (guidelines not yet generated —
    run utils/generate_kb_json.py for the old KB, utils/generate_new_kb_json.py for the new).
    Cached per resolved path.
    """
    path = json_path or _KB_JSON                    # [wrapper-only] default to the OLD KB when no path given
    key = str(path)                                 # [wrapper-only] per-path cache key (old vs new KB cached separately)
    if key in _guidelines_cache:                    # [wrapper-only] return cached dict so each KB loads off disk once
        return _guidelines_cache[key]

    if not path.exists():                           # [wrapper-only] KB JSON not generated yet -> treat as "no guidelines"
        _guidelines_cache[key] = {}                 # [wrapper-only] cache empty dict so we don't re-stat the missing file
        return _guidelines_cache[key]

    with open(path, "r", encoding="utf-8") as f:    # [wrapper-only] read the KB JSON (no run.py analog)
        raw = json.load(f)                          # [wrapper-only] parse {block -> [guidelines]} mapping
    raw.pop("_metadata", None)   # strip metadata key embedded by the generators
    _guidelines_cache[key] = raw                    # [wrapper-only] cache under the resolved path
    return raw                                      # [wrapper-only] hand back the {block -> [guidelines]} dict


# Eagerly loaded at import time — callers can use these directly.
WEAKSPOT_GUIDELINES: Dict[str, List[str]] = load_weakspot_guidelines()               # old KB (HTML-derived)
NEW_WEAKSPOT_GUIDELINES: Dict[str, List[str]] = load_weakspot_guidelines(_NEW_KB_JSON)  # new KB (BU Excel-derived)


# ── Block-type matching ────────────────────────────────────────────────────────

# Ordered list of suffix patterns to strip from ASCET function names.
# Applied iteratively: each pass strips one suffix until no more match.
_SUFFIX_RE = re.compile(
    r"(Param_t|_Param_t|_param_t|_Param|_param"
    r"|_Step|_Update|_Init|_Reset"
    r"|_out|_get|_set|_calc|_value"   # ASCET method-call suffixes (e.g. Srv_RampSwitch_out)
    r"|_t"
    r"|_\d+)$"
)


# [wrapper-only] Map an ASCET function name to a KB block key via suffix-stripping -- no run.py
# analog (run.py never resolves a block against a guideline set).
def find_block_type(
    function_name: str,
    kb: Optional[Dict[str, List[str]]] = None,
) -> Optional[str]:
    """Return the KB block name that best matches *function_name*, or ``None``.

    Matching strategy (tried in order):
    1. Exact match against KB keys
    2. Iteratively strip ASCET suffixes (``Param_t``, ``_t``, ``_Step``, …)
       and retry exact match after each strip
    3. Case-insensitive match for every candidate produced above

    Examples::

        find_block_type("Srv_Debounce")         → "Srv_Debounce"
        find_block_type("Srv_DebounceParam_t")  → "Srv_Debounce"
        find_block_type("Srv_RampSwitchParam_t") → "Srv_RampSwitch"
        find_block_type("LowpassT")             → "LowpassT"  (or None if absent)
        find_block_type("unknown_block")        → None
    """
    if kb is None:                                  # [wrapper-only] default to the OLD KB when caller passes none
        kb = WEAKSPOT_GUIDELINES
    if not kb or not function_name:                 # [wrapper-only] empty KB or empty name -> no possible match
        return None

    # Build a case-insensitive reverse lookup once
    kb_lower: Dict[str, str] = {k.lower(): k for k in kb}  # [wrapper-only] lowercase->original map for step-3 CI match

    # Generate candidates: original name + each suffix-stripped variant
    candidates: List[str] = [function_name]         # [wrapper-only] first candidate is the raw ASCET name
    current = function_name                          # [wrapper-only] rolling name we peel suffixes off of
    while True:                                      # [wrapper-only] strip one ASCET suffix per pass until none match
        m = _SUFFIX_RE.search(current)              # [wrapper-only] find a trailing suffix (Param_t, _t, _Step, ...)
        if not m:                                    # [wrapper-only] no more suffixes -> stop peeling
            break
        current = current[: m.start()]              # [wrapper-only] drop the matched suffix
        if current:                                  # [wrapper-only] keep non-empty stems as additional candidates
            candidates.append(current)

    for cand in candidates:                          # [wrapper-only] try raw name then each stem, in order
        # 1. Exact
        if cand in kb:                               # [wrapper-only] exact KB key hit -> that block
            return cand
        # 2. Case-insensitive
        lo = cand.lower()                            # [wrapper-only] normalize for case-insensitive retry
        if lo in kb_lower:                           # [wrapper-only] CI hit -> return the KB's original-cased key
            return kb_lower[lo]

    return None                                      # [wrapper-only] no candidate matched -> caller falls back to no-KB


# [wrapper-only] Layered KB lookup (new KB -> old KB -> none) feeding M4 coverage scoring in
# evaluation/mbd_metric.py -- no run.py analog (run.py computes NO score and has no KB).
def resolve_guidelines(
    function_name: str,
) -> Tuple[Optional[str], Optional[str], List[str]]:
    """Resolve M4 coverage guidelines for a weakspot's *function_name*, NEW KB first.

    Layered lookup (matches the M4 plan: new -> old -> none):
      1. NEW KB (BU Excel-derived) — if find_block_type resolves it AND the block has guidelines.
      2. OLD KB (HTML-derived)     — fallback.
      3. (None, None, [])          — neither matches -> M4 returns its neutral 0.5.

    Returns (source, block_type, guidelines) where source is "newKB", "KB", or None.
    Both lookups reuse the same find_block_type() suffix-stripping, so no block-name logic
    is duplicated. A block is only served from the NEW KB if it is listed in
    utils/block_to_tc.json (new-only "replace" policy); everything else stays on the old KB.
    """
    if function_name:                               # [wrapper-only] only attempt a lookup for a real weakspot name
        bt = find_block_type(function_name, NEW_WEAKSPOT_GUIDELINES)  # [wrapper-only] layer 1: resolve against NEW KB
        if bt and NEW_WEAKSPOT_GUIDELINES.get(bt):  # [wrapper-only] NEW KB has this block AND it carries guidelines
            return "newKB", bt, NEW_WEAKSPOT_GUIDELINES[bt]  # [wrapper-only] serve NEW KB (source tag "newKB")
        bt = find_block_type(function_name, WEAKSPOT_GUIDELINES)  # [wrapper-only] layer 2: fall back to OLD KB
        if bt and WEAKSPOT_GUIDELINES.get(bt):      # [wrapper-only] OLD KB has this block AND it carries guidelines
            return "KB", bt, WEAKSPOT_GUIDELINES[bt]  # [wrapper-only] serve OLD KB (source tag "KB")
    return None, None, []                           # [wrapper-only] neither KB matched -> M4 uses its neutral 0.5


# [wrapper-only] Render resolved KB guidelines as text for OPTIONAL injection into Prompt 2
# ((corresponds-to) run.py Phase 3b / _step_3b_generate_testcases, run.py:465; run.py's own
# Prompt-2 seed carries NO guidelines). Off by default -- injection lifts M4 cosmetically but
# degrades M7/M2 (see MEMORY "Guideline-injection matrix result"). No run.py analog.
def format_kb_guidelines_block(function_name: str) -> str:
    """Render a weakspot's resolved KB guidelines as a delimited, numbered text block for
    *injection into the test-case generator prompt* (Prompt 2). Returns "" when no KB match,
    so unmapped blocks inject nothing.

    Uses the SAME resolve_guidelines() layering as M4 (new KB -> old KB -> none), read LIVE each
    call — so toggling NEW_WEAKSPOT_GUIDELINES flips both the prompt-injection and M4 scoring in
    lockstep (search new KB -> append to prompt AND use for M4; else old KB).
    """
    source, block_type, guidelines = resolve_guidelines(function_name)  # [wrapper-only] same new->old layering M4 uses
    if not guidelines:                              # [wrapper-only] no KB match -> inject nothing (empty block)
        return ""
    out = [f"## Validated test guidelines for {block_type} ({source}) — cover these scenarios:"]  # [wrapper-only] header line naming the block + KB source
    out += [f"{i}. {g}" for i, g in enumerate(guidelines, 1)]  # [wrapper-only] numbered guideline lines (1-based)
    return "\n".join(out)                           # [wrapper-only] joined text appended to Prompt 2 context when injection is ON
